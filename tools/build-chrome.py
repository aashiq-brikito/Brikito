#!/usr/bin/env python3
"""Make the new header + footer for pages that keep their own layout (blog articles).

Takes the header/footer styles from assets/site.css and scopes every rule under
.v2c, so they can sit on an article page without touching the article's own
styles. Writes:
  assets/chrome.css          scoped header/footer styles
  components/header.html     the header markup (from the pre-rendered homepage)
  components/footer.html     the footer markup
Then run tools/sync-header-footer.py to put them into every article.
"""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
css = open(os.path.join(ROOT, "assets/site.css"), encoding="utf-8").read()
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)

CHROME = re.compile(r"(^|[\s,>+~(])(\.nav\b|\.logo\b|\.mega\b|\.megacon\b|\.grid4\b|\.sheet\b|\.burger\b|\.signin\b|"
                    r"\.progress\b|footer\b|\.btn\b|\.btn-p\b|\.btn-s\b|\.btn-sm\b|\.link\b|\.ch\b|\.wrap\b|\.ico\b|"
                    r"\.chip\b|\.dot\b|\.breathe\b|\.right\b|\.links\b|\.in\b|\.cols\b|\.bottom\b|\.soc\b)")

def items(text):
    """Split CSS into top-level (prelude, body) pairs, keeping @media blocks whole."""
    out, i, n = [], 0, len(text)
    while i < n:
        j = text.find("{", i)
        if j < 0: break
        prelude = text[i:j].strip()
        depth, k = 1, j + 1
        while depth and k < n:
            depth += {"{": 1, "}": -1}.get(text[k], 0); k += 1
        out.append((prelude, text[j + 1:k - 1]))
        i = k
    return out

def scope(sel):
    sel = sel.strip()
    if sel in (":root", "html", "body"): return ".v2c"
    return ".v2c " + sel

def rules(text):
    keep = []
    for pre, body in items(text):
        if pre.startswith("@media"):
            inner = rules(body)
            if inner: keep.append(f"{pre}{{{''.join(inner)}}}")
        elif pre.startswith("@keyframes"):
            if re.search(r"@keyframes\s+(pulse|breathe)\b", pre):
                keep.append(f"{pre.replace('@keyframes ', '@keyframes v2c-')}{{{body}}}")
        elif pre.startswith("@"):
            continue
        elif pre == ":root":
            keep.append(f".v2c{{{body}}}")
        else:
            sels = [x for x in pre.split(",") if CHROME.search(" " + x.strip())]
            if sels:
                keep.append(",".join(scope(x) for x in sels) + "{" + body + "}")
    return keep

out = rules(css)
base = (".v2c{font-family:var(--body);font-size:17px;line-height:1.5;color:var(--ink);letter-spacing:-.011em;"
        "-webkit-font-smoothing:antialiased;text-align:left}"
        ".v2c.v2c-head{display:contents}"
        ".v2c *,.v2c *::before,.v2c *::after{box-sizing:border-box}"
        ".v2c a{color:inherit;text-decoration:none}.v2c img{max-width:100%;display:block}"
        ".v2c button{font:inherit;color:inherit}.v2c p,.v2c h5{margin:0}"
        ".v2c h5{font-family:var(--head)}"
        # article pages have their own stacking; keep the header, menus and progress bar on top
        ".v2c .nav{z-index:1000}.v2c .sheet{z-index:999}.v2c .progress{z-index:1001}")
text = "/* Brikito header + footer for article pages. Generated by tools/build-chrome.py from assets/site.css */\n" + base + "\n" + "\n".join(out) + "\n.v2c .nav{z-index:1000}.v2c .sheet{z-index:999}.v2c .progress{z-index:1001}\n"
text = re.sub(r"\b(animation[^;{}]*?)\b(pulse|breathe)\b", r"\1v2c-\2", text)
open(os.path.join(ROOT, "assets/chrome.css"), "w", encoding="utf-8").write(text)

home = open(os.path.join(ROOT, "index.html"), encoding="utf-8").read()
shell = re.search(r'<div id="shell">(.*?)</div>\n<main id="app">', home, re.S).group(1)
footer = re.search(r"(<footer>.*?</footer>)", home, re.S).group(1)
shell = shell.replace(' class="on"', "")
open(os.path.join(ROOT, "components/header.html"), "w", encoding="utf-8").write(
    '<!-- site-header (generated by tools/build-chrome.py; edit assets/site.js, rebuild) -->\n'
    f'<div class="v2c v2c-head"><div class="progress" aria-hidden="true"></div>{shell}</div>\n<!-- /site-header -->\n')
open(os.path.join(ROOT, "components/footer.html"), "w", encoding="utf-8").write(
    '<!-- site-footer (generated by tools/build-chrome.py) -->\n'
    f'<div class="v2c">{footer}</div>\n<!-- /site-footer -->\n')
print("chrome.css", len(text), "bytes,", len(out), "rules")
